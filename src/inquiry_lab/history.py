import json
import os
from pathlib import Path
from tempfile import TemporaryDirectory
from urllib.parse import quote

RUN_FIELDS = {
    "hypothesis": "仮説",
    "verification": "検証",
    "results": "結果",
    "discussion": "考察",
}
DECISION_FIELDS = {"decision": "判断", "reason": "理由"}
GENERATED = "<!-- Generated by inquiry-lab history render. Edit the JSON source. -->"


def nonempty_line(value: object) -> bool:
    return (
        isinstance(value, str)
        and bool(value)
        and value == value.strip()
        and len(value.splitlines()) == 1
    )


def validate_entry(entry: object) -> dict:
    if not isinstance(entry, dict):
        raise ValueError("history entry must be a JSON object")
    if type(entry.get("sequence")) is not int or not 1 <= entry["sequence"] <= 999999:
        raise ValueError("sequence must be an integer from 1 to 999999")
    common = {"sequence", "kind", "current_state", "references", "depends_on", "title"}
    parents = entry.get("depends_on", [])
    if not isinstance(parents, list) or any(
        type(parent) is not int or not 1 <= parent < entry["sequence"] for parent in parents
    ):
        raise ValueError("depends_on must list earlier sequence numbers")
    if len(set(parents)) != len(parents):
        raise ValueError("depends_on contains duplicate sequence numbers")
    if "title" in entry and not nonempty_line(entry["title"]):
        raise ValueError("title must be a nonempty single line")
    kind = entry.get("kind")
    if kind == "run":
        fields = RUN_FIELDS
        allowed = common | {"run_id", "base_run", *fields}
        base = entry.get("base_run")
        if base is not None and (type(base) is not int or not 1 <= base < entry["sequence"]):
            raise ValueError("base_run must be an earlier run's sequence number")
        if not nonempty_line(entry.get("run_id")):
            raise ValueError("run_id must be a nonempty single line")
    elif kind == "decision":
        fields = DECISION_FIELDS
        allowed = common | set(fields)
    else:
        raise ValueError("kind must be run or decision")
    if unknown := entry.keys() - allowed:
        raise ValueError(f"unknown fields: {', '.join(sorted(unknown))}")
    if not nonempty_line(entry.get("current_state")):
        raise ValueError("current_state must be a nonempty single line")
    for field in fields:
        items = entry.get(field)
        if not isinstance(items, list) or not items or not all(map(nonempty_line, items)):
            raise ValueError(f"{field} must be a nonempty list of single-line strings")
    references = entry.get("references")
    if not isinstance(references, list):
        raise ValueError("references must be a list")
    for ref in references:
        if (
            not isinstance(ref, dict)
            or ref.keys() != {"label", "target"}
            or not all(map(nonempty_line, ref.values()))
        ):
            raise ValueError("each reference needs a single-line label and target")
    return entry


def history_dir(workspace: Path) -> Path:
    if not workspace.is_dir():
        raise ValueError(f"workspace is not a directory: {workspace}")
    directory = workspace / "history"
    if directory.is_symlink():
        raise ValueError(f"history directory is a symlink: {directory}")
    return directory


def read_entry(source: Path) -> dict:
    try:
        record = validate_entry(json.loads(source.read_text(encoding="utf-8")))
        if source.name != f"{record['sequence']:06d}.json":
            raise ValueError("filename must match sequence")
    except ValueError as error:
        raise ValueError(f"{source}: {error}") from error
    return record


def record_entry(workspace: Path, entry: object) -> Path:
    record = validate_entry(entry)
    directory = history_dir(workspace)
    if (base := record.get("base_run")) is not None:
        if read_entry(directory / f"{base:06d}.json")["kind"] != "run":
            raise ValueError(f"base_run does not refer to a run: {base}")
    for parent in record.get("depends_on", []):
        if not (directory / f"{parent:06d}.json").is_file():
            raise ValueError(f"unknown dependency: {parent}")
    directory.mkdir(exist_ok=True)
    path = directory / f"{record['sequence']:06d}.json"
    with TemporaryDirectory(dir=directory) as temporary:
        source = Path(temporary) / "entry"
        source.write_text(
            json.dumps(record, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        # Publish a complete record without replacing a concurrent writer's entry.
        os.link(source, path)
    return path.absolute()


def dependency_diagram(entries: list[dict]) -> list[str]:
    runs = {entry["sequence"] for entry in entries if entry["kind"] == "run"}
    nodes = set()
    arrows = []
    for entry in entries:
        number = entry["sequence"]
        base = entry.get("base_run")
        if base is not None:
            if base not in runs:
                raise ValueError(f"entry {number}: base_run does not refer to a run: {base}")
            nodes.update((base, number))
            arrows.append(f"    e{base} -->|元のrun| e{number}")
        for parent in entry.get("depends_on", []):
            if parent != base:
                nodes.update((parent, number))
                arrows.append(f"    e{parent} --> e{number}")
    if not arrows:
        return []
    missing = nodes - {entry["sequence"] for entry in entries}
    if missing:
        raise ValueError(f"missing dependency entries: {sorted(missing)}")
    lines = [
        "## 分析の依存関係",
        "",
        "矢印は、参照した記録から、それを使った試行・判断へ向かう。",
        "",
        "```mermaid",
        "flowchart TD",
    ]
    for entry in entries:
        number = entry["sequence"]
        if number in nodes:
            title = entry.get("title", entry.get("run_id", "判断"))
            # Encode syntax characters so labels stay text inside the Mermaid block.
            label = "".join(c if c.isalnum() or c in " -" else f"#{ord(c)};" for c in title)
            lines.append(f'    e{number}["{number} · {label}"]')
    lines.extend(arrows)
    return [*lines, "```", ""]


def render_history(workspace: Path) -> Path:
    directory = history_dir(workspace)
    entries = [read_entry(source) for source in sorted(directory.glob("*.json"))]
    if not entries:
        raise ValueError("no recorded history entries")
    latest = entries[-1]
    lines = ["# 作業履歴", "", GENERATED, ""]
    if (workspace / "requests/001-initial.md").is_file():
        lines.extend(["[依頼・目的・判断基準](requests/001-initial.md)", ""])
    lines.extend(dependency_diagram(entries))
    lines.extend(["## 現在地", "", latest["current_state"], ""])
    lines.extend([f"[該当する記録](#entry-{latest['sequence']})", "", "## 試行履歴"])
    for entry in entries:
        is_run = entry["kind"] == "run"
        title = entry["run_id"] if is_run else "判断の記録"
        if "title" in entry:
            title += f"　{entry['title']}"
        lines.extend(["", f'<a id="entry-{entry["sequence"]}"></a>', "", f"### {title}", ""])
        if (base := entry.get("base_run")) is not None:
            lines.extend([f"元のrun　[記録{base}](#entry-{base})", ""])
        if entry.get("depends_on"):
            parents = [f"[記録{n}](#entry-{n})" for n in entry["depends_on"]]
            lines.extend([f"依存元　{'、'.join(parents)}", ""])
        fields = RUN_FIELDS if is_run else DECISION_FIELDS
        for key, label in fields.items():
            lines.append(f"- **{label}**")
            lines.extend(f"  - {item}" for item in entry[key])
        lines.append("- **参考**")
        for ref in entry["references"]:
            label = ref["label"].replace("\\", "\\\\").replace("[", r"\[").replace("]", r"\]")
            target = quote(ref["target"], safe="/:#?=&%+@!$,;~")
            lines.append(f"  - [{label}](<{target}>)")
        if not entry["references"]:
            lines.append("  - なし")
        # Retain earlier checkpoints when later entries change the current state.
        if entry is not latest:
            lines.extend(["", f"この時点の現在地　{entry['current_state']}"])
    path = workspace / "作業履歴.md"
    if path.is_symlink():
        raise ValueError(f"refusing to replace symlink: {path}")
    if path.exists() and GENERATED not in path.read_text(encoding="utf-8").splitlines()[:3]:
        raise ValueError(
            f"refusing to overwrite a document not generated by history render: {path}"
        )
    with TemporaryDirectory(dir=workspace) as temporary:
        source = Path(temporary) / "history.md"
        source.write_text("\n".join(lines) + "\n", encoding="utf-8")
        source.replace(path)
    return path.absolute()
